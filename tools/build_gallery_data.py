#!/usr/bin/env python3
"""
build_gallery_data.py  —  turn a CSV of photos into the map-gallery data file.

Adds new photos to the interactive map gallery without hand-editing JS:
  1. Reads a CSV of  file, lat, lng, title, caption
  2. Copies/optimises each photo into assets/img/gallery/ and makes a -thumb.jpg
  3. Writes assets/js/gallery-map-data.js

CSV format (header row required) — see tools/photos.csv for a ready template:

    file,title,description,lat,lng,place,date
    C:/photos/IMG_2201.jpg,Into the Mist,A foggy pine trail,11.4278,76.6950,Kotagiri,2024-05
    C:/photos/IMG_2210.jpg,Earth from Above,Satellite montage,,,,           <- blank lat/lng = grid only

Columns: file, title, description are used to build the grid + popup.
         lat, lng place the marker (leave both blank for grid-only photos).
         place, date are optional and shown as a small line in the popup.

Usage:
    python tools/build_gallery_data.py tools/photos.csv

Requires Pillow:   pip install pillow
Run it from the project root.
"""
import csv, os, sys, re
from PIL import Image, ImageOps

ROOT      = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GAL_DIR   = os.path.join(ROOT, "assets", "img", "gallery")
DATA_FILE = os.path.join(ROOT, "assets", "js", "gallery-map-data.js")
FULL_MAX  = 1600          # longest edge of the "full" image
THUMB_MAX = 600           # longest edge of the thumbnail
JPEG_Q    = 82


def slugify(name):
    s = re.sub(r"[^a-zA-Z0-9]+", "-", name.strip().lower()).strip("-")
    return s or "photo"


def save_resized(src, dst, max_edge):
    img = ImageOps.exif_transpose(Image.open(src)).convert("RGB")
    img.thumbnail((max_edge, max_edge), Image.LANCZOS)
    img.save(dst, "JPEG", quality=JPEG_Q, optimize=True)


def js_escape(s):
    return (s or "").replace("\\", "\\\\").replace('"', '\\"')


def main(csv_path):
    if not os.path.isfile(csv_path):
        sys.exit("CSV not found: " + csv_path)
    os.makedirs(GAL_DIR, exist_ok=True)

    entries = []
    with open(csv_path, newline="", encoding="utf-8-sig") as f:
        for row in csv.DictReader(f):
            src = (row.get("file") or "").strip()
            if not src or src.startswith("#"):   # skip blank + comment rows
                continue
            title   = (row.get("title") or "").strip()
            # accept either "description" or the older "caption" header
            caption = (row.get("description") or row.get("caption") or "").strip()
            lat = (row.get("lat") or "").strip()
            lng = (row.get("lng") or "").strip()
            place = (row.get("place") or "").strip()
            date  = (row.get("date") or "").strip()

            slug  = slugify(title or os.path.splitext(os.path.basename(src))[0])
            full  = "%s.jpg" % slug
            thumb = "%s-thumb.jpg" % slug

            if os.path.isfile(src):
                save_resized(src, os.path.join(GAL_DIR, full),  FULL_MAX)
                save_resized(src, os.path.join(GAL_DIR, thumb), THUMB_MAX)
                print("  ok  %-28s -> %s (+thumb)" % (os.path.basename(src), full))
            else:
                print("  !!  source missing, keeping paths only:", src)

            entries.append({
                "title": title, "caption": caption,
                "thumb": "assets/img/gallery/" + thumb,
                "full":  "assets/img/gallery/" + full,
                "lat": lat, "lng": lng,
                "place": place, "date": date,
            })

    lines = []
    for e in entries:
        lat = e["lat"] if e["lat"] else "null"
        lng = e["lng"] if e["lng"] else "null"
        lines.append(
            "  {\n"
            '    title:   "%s",\n'
            '    caption: "%s",\n'
            '    place:   "%s",\n'
            '    date:    "%s",\n'
            '    thumb:   "%s",\n'
            '    full:    "%s",\n'
            "    lat: %s, lng: %s\n"
            "  }" % (js_escape(e["title"]), js_escape(e["caption"]),
                     js_escape(e["place"]), js_escape(e["date"]),
                     e["thumb"], e["full"], lat, lng)
        )

    out = (
        "/* Auto-generated by tools/build_gallery_data.py — edit the CSV and re-run. */\n"
        "window.GALLERY_PHOTOS = [\n" + ",\n".join(lines) + "\n];\n"
    )
    with open(DATA_FILE, "w", encoding="utf-8") as f:
        f.write(out)
    print("\nWrote %d photos to %s" % (len(entries), os.path.relpath(DATA_FILE, ROOT)))


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit("Usage: python tools/build_gallery_data.py <photos.csv>")
    main(sys.argv[1])
